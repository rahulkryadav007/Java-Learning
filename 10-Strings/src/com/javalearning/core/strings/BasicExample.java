package com.javalearning.core.strings;

public class BasicExample {
    public static void main(String[] args) {
        String name = "Rahul"; // String mein text store kar rahe hain.
        System.out.println(name.length()); // Characters ki count.
        System.out.println(name.charAt(0)); // First character.
        System.out.println(name.toUpperCase()); // Text ko uppercase kar rahe hain.
    }
}
